/**
 * SYNTHETIC registry for Bungoma county (code 039) used by the seed, the
 * registry-import fixtures and tests.
 *
 * Only the county code and name are real (public reference data). Every
 * constituency, ward, polling centre, station, code and registered-voter figure
 * below is invented and labelled SYNTHETIC. It is not the IEBC station list.
 *
 * Shape: 9 constituencies × 5 wards × 2 polling centres. Wards 1–2 have two
 * streams per centre; wards 3–5 have two streams at centre 1 and one at centre 2.
 * That gives 17 stations per constituency and 153 stations in total.
 */
import { createHash } from 'node:crypto';
import { toCsv } from '@ngao360/shared';

export const SYNTHETIC_REGISTRY_VERSION = 'SYNTHETIC-2027-R1';
export const SYNTHETIC_REGISTRY_SOURCE =
  'SYNTHETIC rehearsal registry generated by the NGAO360 seed. Not IEBC data; codes, names and registered-voter figures are invented.';
export const SYNTHETIC_LOCATION_SOURCE = 'SYNTHETIC (no real location)';

export const SYNTHETIC_CONSTITUENCIES = [
  { key: 'c1', code: 'SYN-C01', name: 'Synthetic Constituency North', short: 'North' },
  { key: 'c2', code: 'SYN-C02', name: 'Synthetic Constituency South', short: 'South' },
  { key: 'c3', code: 'SYN-C03', name: 'Synthetic Constituency East', short: 'East' },
  { key: 'c4', code: 'SYN-C04', name: 'Synthetic Constituency West', short: 'West' },
  { key: 'c5', code: 'SYN-C05', name: 'Synthetic Constituency Central', short: 'Central' },
  { key: 'c6', code: 'SYN-C06', name: 'Synthetic Constituency Highlands', short: 'Highlands' },
  { key: 'c7', code: 'SYN-C07', name: 'Synthetic Constituency Lowlands', short: 'Lowlands' },
  { key: 'c8', code: 'SYN-C08', name: 'Synthetic Constituency Riverside', short: 'Riverside' },
  { key: 'c9', code: 'SYN-C09', name: 'Synthetic Constituency Lakeside', short: 'Lakeside' },
] as const;

export const WARDS_PER_CONSTITUENCY = 5;
export const CENTRES_PER_WARD = 2;

export interface SyntheticStationRow {
  county_code: string;
  county_name: string;
  constituency_code: string;
  constituency_name: string;
  ward_code: string;
  ward_name: string;
  centre_code: string;
  centre_name: string;
  station_code: string;
  station_name: string;
  registered_voters: number | null;
  stream_number: number;
  latitude: number | null;
  longitude: number | null;
  location_source: string;
  /** Seed key used by demo role assignments, e.g. "c1", "c1w1", "s1". Not exported to CSV. */
  keys: { constituency: string; ward: string; centre: string; station: string };
}

/** Plausible, deterministic registered-voter figure (350–679) from the station code. */
export function syntheticRegisteredVoters(stationCode: string): number {
  const h = createHash('sha256').update(`ngao360-synthetic:${stationCode}`).digest();
  return 350 + (h.readUInt32BE(0) % 330);
}

export function syntheticBungomaRows(): SyntheticStationRow[] {
  const rows: SyntheticStationRow[] = [];
  let stationIndex = 0;
  for (const c of SYNTHETIC_CONSTITUENCIES) {
    for (let w = 1; w <= WARDS_PER_CONSTITUENCY; w++) {
      const wardCode = `${c.code}-W0${w}`;
      const wardName = `${c.short} Ward ${w} (synthetic)`;
      for (let p = 1; p <= CENTRES_PER_WARD; p++) {
        const centreCode = `${wardCode}-P0${p}`;
        const centreName = `Synthetic Primary School ${c.key.toUpperCase()}${w}${p}`;
        const streams = w <= 2 || p === 1 ? 2 : 1;
        for (let s = 1; s <= streams; s++) {
          stationIndex++;
          const stationCode = `${centreCode}-S0${s}`;
          rows.push({
            county_code: '039',
            county_name: 'Bungoma',
            constituency_code: c.code,
            constituency_name: c.name,
            ward_code: wardCode,
            ward_name: wardName,
            centre_code: centreCode,
            centre_name: centreName,
            station_code: stationCode,
            station_name: `${centreName} — Stream ${s}`,
            registered_voters: syntheticRegisteredVoters(stationCode),
            stream_number: s,
            latitude: null,
            longitude: null,
            location_source: SYNTHETIC_LOCATION_SOURCE,
            keys: { constituency: c.key, ward: `${c.key}w${w}`, centre: `${c.key}w${w}p${p}`, station: `s${stationIndex}` },
          });
        }
      }
    }
  }
  return rows;
}

/** Column order of the documented CSV contract (RegistryImportResultSchema), then the optional extras. */
export const REGISTRY_CSV_COLUMN_ORDER = [
  'county_code',
  'county_name',
  'constituency_code',
  'constituency_name',
  'ward_code',
  'ward_name',
  'centre_code',
  'centre_name',
  'station_code',
  'station_name',
  'registered_voters',
  'stream_number',
  'latitude',
  'longitude',
  'location_source',
] as const;

export function rowsToCsv(rows: readonly Omit<SyntheticStationRow, 'keys'>[]): string {
  return toCsv(
    REGISTRY_CSV_COLUMN_ORDER,
    rows.map((r) => REGISTRY_CSV_COLUMN_ORDER.map((col) => r[col])),
  );
}

/**
 * A second registry version for demonstrating versioned imports: one station
 * withdrawn, two added, one renamed, one ward renamed and some registered-voter
 * figures revised. Still entirely synthetic.
 */
export function syntheticBungomaAmendmentRows(): SyntheticStationRow[] {
  const base = syntheticBungomaRows();
  const out = base
    .filter((r) => r.station_code !== 'SYN-C09-W05-P02-S01')
    .map((r) => {
      const row = { ...r };
      if (row.station_code === 'SYN-C03-W01-P01-S01') row.station_name = 'Synthetic Primary School C311 (renamed) — Stream 1';
      if (row.ward_code === 'SYN-C04-W02') row.ward_name = 'West Ward 2 Upper (synthetic)';
      if (row.constituency_code === 'SYN-C05' && row.stream_number === 1 && row.registered_voters !== null) {
        row.registered_voters = row.registered_voters + 12;
      }
      return row;
    });
  const template = base.find((r) => r.station_code === 'SYN-C01-W01-P01-S02')!;
  for (const s of [3, 4]) {
    out.push({
      ...template,
      station_code: `SYN-C01-W01-P01-S0${s}`,
      station_name: `Synthetic Primary School C111 — Stream ${s}`,
      stream_number: s,
      registered_voters: syntheticRegisteredVoters(`SYN-C01-W01-P01-S0${s}`),
      keys: { ...template.keys, station: `new-${s}` },
    });
  }
  return out;
}
