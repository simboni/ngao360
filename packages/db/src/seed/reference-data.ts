/**
 * Reference-data seed for the demo tenant: the 2027 General Election cycle, all
 * 47 counties (real public codes), a SYNTHETIC Bungoma registry (9
 * constituencies, 45 wards, 90 polling centres, 153 stations), tally centres
 * and a Governor contest with four obviously fictional candidates.
 *
 * The registry rows go through the same CSV validation as a real import
 * (validateRegistryCsv) and an import report is logged as an audit event, so
 * the seeded registry looks exactly like an imported, approved one.
 * Idempotent: units are found by type + code before anything is created.
 */
import { randomUUID } from 'node:crypto';
import type { GeographicUnitType, PrismaClient } from '@prisma/client';
import { AUDIT_ACTIONS } from '@ngao360/shared';
import { KENYA_COUNTIES, validateRegistryCsv } from '@ngao360/shared/dist/reference';
import { canonicalJson, hashJson, sha256Hex } from '../security';
import {
  rowsToCsv,
  SYNTHETIC_REGISTRY_SOURCE,
  SYNTHETIC_REGISTRY_VERSION,
  syntheticBungomaRows,
} from './synthetic-bungoma';

export const DEMO_CYCLE_NAME = '2027 General Election';
/** Name used by earlier seeds; renamed in place so re-seeding never duplicates the cycle. */
const LEGACY_CYCLE_NAMES = ['2027 General Election rehearsal (synthetic)'];
export const COUNTY_SOURCE_VERSION = 'KE-COUNTIES-CONSTITUTION-2010';
export const BUNGOMA_CODE = '039';

export interface ReferenceSeedResult {
  cycleId: string;
  registryVersionId: string;
  countyId: string;
  contestId: string;
  /** Seed keys → ids: 'county', 'c1'…'c9', 'c1w1'…, 'c1w1p1'… */
  units: Map<string, string>;
  /** Seed keys → station ids: 's1'…'s153'. */
  stations: Map<string, string>;
  counties: number;
}

const FICTIONAL_CANDIDATES: Array<[name: string, party: string | null]> = [
  ['Amani Synthetic Wekesa', 'Party Alpha (synthetic)'],
  ['Baraka Synthetic Nanjala', 'Party Beta (synthetic)'],
  ['Chanya Synthetic Wafula', null],
  ['Dalili Synthetic Simiyu', 'Party Gamma (synthetic)'],
];

/** Write an audit event with the same hashing as the API's AuditService. */
async function seedAuditEvent(
  prisma: PrismaClient,
  e: { tenantId: string; actorId: string | null; action: string; entityType: string; entityId: string; after: unknown; reason?: string },
) {
  const occurredAt = new Date();
  const beforeHash = hashJson(null);
  const afterHash = hashJson(e.after);
  const core = {
    tenantId: e.tenantId,
    actorId: e.actorId,
    actorType: e.actorId ? 'USER' : 'SYSTEM',
    action: e.action,
    entityType: e.entityType,
    entityId: e.entityId,
    beforeHash,
    afterHash,
    reason: e.reason ?? null,
    requestId: null,
    occurredAt: occurredAt.toISOString(),
  };
  await prisma.auditEvent.create({
    data: {
      tenantId: e.tenantId,
      actorId: e.actorId,
      actorType: e.actorId ? 'USER' : 'SYSTEM',
      action: e.action,
      entityType: e.entityType,
      entityId: e.entityId,
      beforeHash,
      afterHash,
      after: e.after as object,
      reason: e.reason ?? null,
      eventHash: sha256Hex(canonicalJson(core)),
      occurredAt,
    },
  });
}

export async function seedReferenceData(prisma: PrismaClient, tenantId: string): Promise<ReferenceSeedResult> {
  /* ------------------------------ Election cycle ----------------------------- */
  const existingCycle = await prisma.electionCycle.findFirst({
    where: { tenantId, name: { in: [DEMO_CYCLE_NAME, ...LEGACY_CYCLE_NAMES] } },
  });
  const cycleData = {
    name: DEMO_CYCLE_NAME,
    electionDate: new Date('2027-08-10T00:00:00Z'),
    jurisdiction: 'Kenya',
    legalConfigVersion: 'LN72-2017-baseline',
    status: 'ACTIVE' as const,
    dataProvenance: 'SYNTHETIC' as const,
    officialSources: [
      {
        title: 'Elections (General) (Amendment) Regulations, 2017 — Legal Notice No. 72 of 2017',
        reference: 'Baseline only; revalidate against the 2027 IEBC forms and directions before production',
      },
      {
        title: 'Constitution of Kenya, 2010 — First Schedule (counties)',
        reference: 'County codes and names (public reference data)',
      },
    ],
  };
  const cycle = existingCycle
    ? await prisma.electionCycle.update({ where: { id: existingCycle.id }, data: cycleData })
    : await prisma.electionCycle.create({ data: { tenantId, ...cycleData } });

  /* --------------------------------- Registry -------------------------------- */
  const registry = await prisma.registryVersion.upsert({
    where: { tenantId_electionCycleId_version: { tenantId, electionCycleId: cycle.id, version: SYNTHETIC_REGISTRY_VERSION } },
    create: {
      tenantId,
      electionCycleId: cycle.id,
      version: SYNTHETIC_REGISTRY_VERSION,
      source: SYNTHETIC_REGISTRY_SOURCE,
      status: 'DRAFT',
      notes: 'SYNTHETIC. Generated by packages/db/src/seed/synthetic-bungoma.ts (fixture: fixtures/registry/bungoma-synthetic-2027-r1.csv).',
    },
    update: { source: SYNTHETIC_REGISTRY_SOURCE },
  });

  /* ------------------------------- Geography --------------------------------- */
  const units = new Map<string, string>();
  const stations = new Map<string, string>();

  const ensureUnit = async (
    type: GeographicUnitType,
    code: string,
    name: string,
    parent: { id: string; path: string } | null,
    sourceVersion: string,
    registryVersionId: string | null,
  ): Promise<{ id: string; path: string }> => {
    const found = await prisma.geographicUnit.findFirst({
      where: { tenantId, electionCycleId: cycle.id, type, officialCode: code, parentId: parent?.id ?? null },
      orderBy: { createdAt: 'asc' },
    });
    if (found) return { id: found.id, path: found.path };
    const id = randomUUID();
    const path = `${parent?.path ?? '/'}${id}/`;
    await prisma.geographicUnit.create({
      data: { id, tenantId, electionCycleId: cycle.id, registryVersionId, type, officialCode: code, officialName: name, parentId: parent?.id ?? null, path, sourceVersion },
    });
    return { id, path };
  };

  // All 47 counties: real public codes and names.
  const countyUnits = new Map<string, { id: string; path: string }>();
  for (const c of KENYA_COUNTIES) {
    countyUnits.set(c.code, await ensureUnit('COUNTY', c.code, c.name, null, COUNTY_SOURCE_VERSION, null));
  }
  const bungoma = countyUnits.get(BUNGOMA_CODE)!;
  units.set('county', bungoma.id);

  // Synthetic registry rows, validated exactly like an uploaded CSV.
  const generated = syntheticBungomaRows();
  const csv = rowsToCsv(generated);
  const { rows, report } = validateRegistryCsv(csv, {
    registryVersionId: registry.id,
    version: SYNTHETIC_REGISTRY_VERSION,
    source: SYNTHETIC_REGISTRY_SOURCE,
    publicationDate: null,
    changeNotes: 'Initial SYNTHETIC registry loaded by the seed',
    sourceFileName: 'bungoma-synthetic-2027-r1.csv',
    sourceFileSha256: sha256Hex(csv),
    importedAt: new Date().toISOString(),
  });
  if (report.totals.errors > 0) throw new Error(`Synthetic registry failed validation: ${JSON.stringify(report.issues.slice(0, 5))}`);

  const keysByCode = new Map(generated.map((g) => [g.station_code, g.keys]));
  const sv = SYNTHETIC_REGISTRY_VERSION;
  for (const r of rows) {
    const keys = keysByCode.get(r.stationCode)!;
    const constituency = await ensureUnit('CONSTITUENCY', r.constituencyCode, r.constituencyName, bungoma, sv, registry.id);
    const ward = await ensureUnit('WARD', r.wardCode, r.wardName, constituency, sv, registry.id);
    const centre = await ensureUnit('POLLING_CENTRE', r.centreCode!, r.centreName!, ward, sv, registry.id);
    units.set(keys.constituency, constituency.id);
    units.set(keys.ward, ward.id);
    units.set(keys.centre, centre.id);
    const data = {
      geographicUnitId: centre.id,
      countyId: bungoma.id,
      constituencyId: constituency.id,
      wardId: ward.id,
      pollingCentreId: centre.id,
      name: r.stationName,
      streamNumber: r.streamNumber,
      registeredVoters: r.registeredVoters,
      locationSource: r.locationSource,
    };
    const station = await prisma.pollingStation.upsert({
      where: { tenantId_registryVersionId_code: { tenantId, registryVersionId: registry.id, code: r.stationCode } },
      create: { tenantId, electionCycleId: cycle.id, registryVersionId: registry.id, code: r.stationCode, ...data },
      update: data,
    });
    stations.set(keys.station, station.id);
  }
  const stationCount = await prisma.pollingStation.count({ where: { registryVersionId: registry.id } });
  await prisma.registryVersion.update({ where: { id: registry.id }, data: { stationCount } });

  // Import report (once), so GET /import-status shows how the registry was loaded.
  const logged = await prisma.auditEvent.count({
    where: { tenantId, entityType: 'RegistryVersion', entityId: registry.id, action: AUDIT_ACTIONS.REFERENCE_IMPORTED },
  });
  if (logged === 0) {
    report.diff = { comparedWithVersion: null, added: rows.length, removed: 0, renamed: 0, moved: 0, registeredVotersChanged: 0, unchanged: 0, samples: { added: rows.slice(0, 200).map((r) => r.stationCode), removed: [], renamed: [], moved: [], registeredVotersChanged: [] } };
    await seedAuditEvent(prisma, {
      tenantId,
      actorId: null,
      action: AUDIT_ACTIONS.REFERENCE_IMPORTED,
      entityType: 'RegistryVersion',
      entityId: registry.id,
      after: { status: 'COMPLETED', unitsCreated: units.size, stationsCreated: rows.length, rowsRejected: 0, report },
      reason: 'Seed: SYNTHETIC registry',
    });
  }

  /* ------------------------------ Tally centres ------------------------------ */
  const constituencyCodes = [...new Set(rows.map((r) => [r.constituencyCode, r.constituencyName] as const).map((x) => x.join('|')))];
  for (const entry of constituencyCodes) {
    const [code, name] = entry.split('|') as [string, string];
    const unit = await prisma.geographicUnit.findFirstOrThrow({ where: { tenantId, electionCycleId: cycle.id, type: 'CONSTITUENCY', officialCode: code } });
    await upsertTallyCentre(prisma, tenantId, cycle.id, 'CONSTITUENCY', `TC-${code}`, `${name} tallying centre`, unit.id);
  }
  await upsertTallyCentre(prisma, tenantId, cycle.id, 'COUNTY', `TC-${BUNGOMA_CODE}`, 'Bungoma county tallying centre (synthetic)', bungoma.id);

  /* -------------------------- Governor contest -------------------------- */
  let contest = await prisma.contest.findFirst({
    where: { tenantId, electionCycleId: cycle.id, officeType: 'GOVERNOR', geographicUnitId: bungoma.id },
  });
  if (!contest) {
    contest = await prisma.contest.create({
      data: {
        tenantId,
        electionCycleId: cycle.id,
        officeType: 'GOVERNOR',
        name: 'County Governor — Bungoma (synthetic rehearsal)',
        geographicUnitId: bungoma.id,
        formSeries: '37',
        status: 'ACTIVE',
      },
    });
  }
  for (const [i, [name, party]] of FICTIONAL_CANDIDATES.entries()) {
    await prisma.candidateReference.upsert({
      where: { tenantId_contestId_ballotOrder: { tenantId, contestId: contest.id, ballotOrder: i + 1 } },
      create: {
        tenantId,
        contestId: contest.id,
        ballotOrder: i + 1,
        candidateNameAsPublished: name,
        partyLabel: party,
        isIndependent: party === null,
        referenceCode: `SYN-GOV-039-${i + 1}`,
        source: 'SYNTHETIC rehearsal candidate list (fictional names)',
      },
      update: { candidateNameAsPublished: name, partyLabel: party, isIndependent: party === null },
    });
  }

  return {
    cycleId: cycle.id,
    registryVersionId: registry.id,
    countyId: bungoma.id,
    contestId: contest.id,
    units,
    stations,
    counties: countyUnits.size,
  };
}

/** Mark the seeded registry APPROVED by a named approving user (blueprint 6.2 source metadata). */
export async function approveSeedRegistry(prisma: PrismaClient, tenantId: string, registryVersionId: string, approverId: string) {
  const current = await prisma.registryVersion.findUniqueOrThrow({ where: { id: registryVersionId } });
  if (current.status === 'APPROVED' && current.approvedById) return;
  await prisma.registryVersion.updateMany({
    where: { tenantId, electionCycleId: current.electionCycleId, status: 'APPROVED', id: { not: registryVersionId } },
    data: { status: 'SUPERSEDED' },
  });
  await prisma.registryVersion.update({
    where: { id: registryVersionId },
    data: { status: 'APPROVED', approvedById: approverId, approvedAt: current.approvedAt ?? new Date() },
  });
  await seedAuditEvent(prisma, {
    tenantId,
    actorId: approverId,
    action: AUDIT_ACTIONS.REGISTRY_APPROVED,
    entityType: 'RegistryVersion',
    entityId: registryVersionId,
    after: { status: 'APPROVED', version: current.version, stationCount: current.stationCount },
    reason: 'Seed: SYNTHETIC registry approved for rehearsal',
  });
}

async function upsertTallyCentre(
  prisma: PrismaClient,
  tenantId: string,
  electionCycleId: string,
  level: 'CONSTITUENCY' | 'COUNTY',
  code: string,
  name: string,
  geographicUnitId: string,
) {
  await prisma.tallyCentre.upsert({
    where: { tenantId_electionCycleId_code: { tenantId, electionCycleId, code } },
    create: { tenantId, electionCycleId, level, code, name, geographicUnitId },
    update: { name, geographicUnitId },
  });
}
