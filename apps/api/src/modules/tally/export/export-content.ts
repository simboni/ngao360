import {
  HASH_CAVEAT,
  PARALLEL_TALLY_BANNER,
  PARALLEL_TALLY_DISCLAIMER,
} from '@ngao360/shared';
import type { ExportDocument } from './document';

export const METHODOLOGY_LINES = [
  'Source basis: copies of polling-station result forms received through authorised channels and stored unaltered with a SHA-256 hash.',
  'Capture: a clerk transcribed every value from the source image; any change records the old value, new value, person, time and reason.',
  'Verification: a second authorised person, different from the submitter and from anyone who entered values, checked each record against the source.',
  'Inclusion: only canonical records with status "Verified for parallel tally" are included in the totals. Received, transcribed, awaiting review, flagged and excluded records are reported separately.',
  'Denominator: expected stations come from the approved station registry version named below. Stations without a verified record are reported as missing and are never counted as zero votes.',
  'Shares are percentages of verified valid votes only. Candidates are listed in ballot order.',
  'Snapshots are immutable. A later verified record produces a new snapshot; it never rewrites this one.',
];

export interface ExportContentInput {
  snapshot: {
    id: string;
    reference: string;
    contentHash: string;
    calculationVersion: string;
    createdAt: string;
    createdByName: string;
    releasedAt: string | null;
    geographyLabel: string;
    registryVersionLabel: string | null;
    note: string | null;
  };
  cycleName: string;
  provenanceLabel: string;
  /** "HISTORICAL DEMO / SIMULATED DATA" lines (label, notice, notes) for a historical demo; empty otherwise. */
  dataLabelLines?: string[];
  contestName: string;
  officeLabel: string;
  stationFormNumber: string;
  coverage: {
    expectedStations: number;
    received: number;
    transcribed: number;
    awaitingReview: number;
    verified: number;
    flagged: number;
    excluded: number;
    missing: number;
    verifiedPercent: number;
  };
  totals: {
    totalVerifiedValidVotes: number;
    rejectedBallots: number;
    candidates: Array<{
      ballotOrder: number;
      candidateNameAsPublished: string;
      partyLabel: string | null;
      verifiedVotes: number;
      shareOfVerifiedValidVotes: number;
    }>;
  };
  stations: Array<{
    code: string;
    name: string;
    coverageStatus: string;
    submissionReference: string | null;
    totalValidVotes: number | null;
    candidateVotes: Record<string, number> | null;
  }> | null;
  candidateOrder: Array<{ id: string; label: string }>;
  manifest: Array<{
    submissionReference: string;
    stationCode: string | null;
    fileSha256: string;
    submittedBy: string;
    verifiedBy: string;
    verifiedAt: string | null;
  }>;
  generatedAt: string;
  generatedByName: string;
  format: string;
}

/** Build the export document from an immutable snapshot (same content for every format). */
export function buildExportDocument(i: ExportContentInput): ExportDocument {
  const c = i.coverage;
  const sections: ExportDocument['sections'] = [
    {
      kind: 'text',
      name: 'Disclaimer',
      lines: [
        PARALLEL_TALLY_BANNER,
        PARALLEL_TALLY_DISCLAIMER,
        ...(i.dataLabelLines ?? []),
        `Data provenance: ${i.provenanceLabel}`,
        HASH_CAVEAT,
      ],
    },
    {
      kind: 'table',
      name: 'Snapshot',
      header: ['Property', 'Value'],
      rows: [
        ['Snapshot reference', i.snapshot.reference],
        ['Snapshot ID', i.snapshot.id],
        ['Snapshot content hash (SHA-256)', i.snapshot.contentHash],
        ['Calculation version', i.snapshot.calculationVersion],
        ['Snapshot created (UTC)', i.snapshot.createdAt],
        ['Snapshot created by', i.snapshot.createdByName],
        ['Internal release (UTC)', i.snapshot.releasedAt ?? 'Not released'],
        ['Election cycle', i.cycleName],
        ['Contest', `${i.contestName} (${i.officeLabel})`],
        ['Station-level form', i.stationFormNumber],
        ['Geography', i.snapshot.geographyLabel],
        ['Approved registry version (denominator)', i.snapshot.registryVersionLabel ?? 'No approved registry version'],
        ['Snapshot note', i.snapshot.note ?? ''],
        ['Export format', i.format],
        ['Export generated (UTC)', i.generatedAt],
        ['Export generated by', i.generatedByName],
      ],
    },
    { kind: 'text', name: 'Methodology', lines: METHODOLOGY_LINES },
    {
      kind: 'table',
      name: 'Coverage',
      header: ['Measure', 'Stations'],
      rows: [
        ['Expected stations (denominator)', c.expectedStations],
        ['Forms received', c.received],
        ['Transcribed', c.transcribed],
        ['Awaiting second review', c.awaitingReview],
        ['Verified for parallel tally (included)', c.verified],
        ['Flagged', c.flagged],
        ['Excluded from aggregate', c.excluded],
        ['Missing (not counted as zero)', c.missing],
        ['Verified coverage %', c.verifiedPercent],
      ],
    },
    {
      kind: 'table',
      name: 'Candidate totals',
      header: ['Ballot order', 'Candidate (as published)', 'Party', 'Verified votes', 'Share of verified valid votes %'],
      rows: [
        ...i.totals.candidates.map((t) => [
          t.ballotOrder,
          t.candidateNameAsPublished,
          t.partyLabel ?? '',
          t.verifiedVotes,
          t.shareOfVerifiedValidVotes,
        ]),
        ['', 'Total verified valid votes', '', i.totals.totalVerifiedValidVotes, ''],
        ['', 'Rejected ballots (included stations)', '', i.totals.rejectedBallots, ''],
        ['', `Included stations: ${c.verified} of ${c.expectedStations} expected`, '', '', ''],
      ],
    },
  ];
  if (i.stations) {
    sections.push({
      kind: 'table',
      name: 'Stations',
      header: [
        'Station code',
        'Station name',
        'Record status',
        'Submission',
        'Total valid votes',
        ...i.candidateOrder.map((x) => x.label),
      ],
      rows: i.stations.map((s) => [
        s.code,
        s.name,
        s.coverageStatus,
        s.submissionReference ?? '',
        s.totalValidVotes,
        ...i.candidateOrder.map((x) => (s.candidateVotes ? (s.candidateVotes[x.id] ?? null) : null)),
      ]),
    });
  }
  sections.push({
    kind: 'table',
    name: 'Audit manifest',
    header: ['Submission', 'Station code', 'Source file SHA-256', 'Submitted by', 'Verified by', 'Verified at (UTC)'],
    rows: i.manifest.map((m) => [
      m.submissionReference,
      m.stationCode,
      m.fileSha256,
      m.submittedBy,
      m.verifiedBy,
      m.verifiedAt,
    ]),
  });
  const demo = i.dataLabelLines?.[0];
  return {
    title: `NGAO TALLY internal parallel tally export - ${i.snapshot.reference}${demo ? ` - ${demo}` : ''}`,
    sections,
  };
}
