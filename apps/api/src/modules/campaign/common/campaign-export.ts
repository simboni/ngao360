/**
 * Campaign exports (report builder, finance registers, attendance, breach
 * timelines): every file starts with a header block naming the report, the
 * generation time (Africa/Nairobi and UTC), the generator, filters, applied
 * scope, data classification and any dataset disclaimer. Rendering reuses the
 * format-neutral export writers (CSV with formula-injection protection, XLSX,
 * PDF). Files are stored immutably with purpose EXPORT.
 */
import type { StoredFile, TenantTx } from '@ngao360/db';
import type { ExportFormat, SensitivityLevel } from '@ngao360/shared';
import type { AuthContext } from '../../../auth/auth.types';
import type { StorageService } from '../../../storage/storage.service';
import { renderCsv } from '../../tally/export/csv';
import type { Cell, ExportDocument } from '../../tally/export/document';
import { renderPdf } from '../../tally/export/pdf';
import { renderXlsx } from '../../tally/export/xlsx';

export const EXPORT_FORMAT_META: Record<ExportFormat, { mime: string; ext: string }> = {
  CSV: { mime: 'text/csv', ext: 'csv' },
  XLSX: { mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', ext: 'xlsx' },
  PDF: { mime: 'application/pdf', ext: 'pdf' },
};

export const CLASSIFICATION_LABELS: Record<SensitivityLevel, string> = {
  PUBLIC: 'PUBLIC',
  INTERNAL: 'INTERNAL – do not share outside the organisation',
  CONFIDENTIAL: 'CONFIDENTIAL – authorised recipients only',
  HIGHLY_RESTRICTED: 'HIGHLY RESTRICTED – named recipients only',
};

export function nairobiTime(d: Date): string {
  const s = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Africa/Nairobi',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  }).format(d);
  return `${s} (Africa/Nairobi)`;
}

export interface ExportHeader {
  title: string;
  generatedAt: Date;
  generatedBy: string;
  filtersDescription: string;
  appliedScope: string;
  classification: SensitivityLevel;
  disclaimer?: string | null;
  extraLines?: string[];
}

export function headerLines(h: ExportHeader): string[] {
  return [
    `Report: ${h.title}`,
    `Generated: ${nairobiTime(h.generatedAt)} / ${h.generatedAt.toISOString()} (UTC)`,
    `Generated by: ${h.generatedBy}`,
    `Filters: ${h.filtersDescription || 'None'}`,
    `Scope: ${h.appliedScope}`,
    `Data classification: ${CLASSIFICATION_LABELS[h.classification]}`,
    ...(h.disclaimer ? [`Disclaimer: ${h.disclaimer}`] : []),
    ...(h.extraLines ?? []),
  ];
}

export function buildDocument(h: ExportHeader, tables: Array<{ name: string; header: string[]; rows: Cell[][] }>): ExportDocument {
  return {
    title: h.title,
    sections: [{ kind: 'text', name: 'About this export', lines: headerLines(h) }, ...tables.map((t) => ({ kind: 'table' as const, ...t }))],
  };
}

export function renderDocument(doc: ExportDocument, format: ExportFormat, h: ExportHeader): Buffer {
  switch (format) {
    case 'CSV':
      return renderCsv(doc);
    case 'XLSX':
      return renderXlsx(doc);
    case 'PDF':
      return renderPdf(doc, `${h.classification}${h.disclaimer ? `. ${h.disclaimer}` : ''}`);
  }
}

/** Render, store immutably (purpose EXPORT) and return the stored file. */
export async function storeExport(
  storage: StorageService,
  tx: TenantTx,
  auth: AuthContext,
  h: ExportHeader,
  tables: Array<{ name: string; header: string[]; rows: Cell[][] }>,
  format: ExportFormat,
  filenameStem: string,
): Promise<StoredFile> {
  const doc = buildDocument(h, tables);
  const buffer = renderDocument(doc, format, h);
  const meta = EXPORT_FORMAT_META[format];
  const { file } = await storage.storeImmutable(
    {
      tenantId: auth.tenantId,
      uploadedById: auth.userId,
      buffer,
      declaredMimeType: meta.mime,
      originalFilename: `ngao-${filenameStem}-${h.generatedAt.toISOString().replace(/[:.]/g, '-')}.${meta.ext}`,
      purpose: 'EXPORT',
    },
    tx,
  );
  return file;
}

/** Cell value for exports (money as major units string with currency kept in its own column). */
export function exportCell(v: unknown): Cell {
  if (v === null || v === undefined) return null;
  if (typeof v === 'number') return v;
  if (typeof v === 'boolean') return v ? 'Yes' : 'No';
  if (Array.isArray(v)) return v.join('; ');
  if (v instanceof Date) return v.toISOString();
  return String(v);
}
